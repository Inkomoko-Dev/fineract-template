package org.apache.fineract.portfolio.loanaccount.domain;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNull;

import java.math.BigDecimal;
import java.math.MathContext;
import java.math.RoundingMode;
import java.time.LocalDate;
import java.util.HashMap;
import java.util.Map;
import org.apache.fineract.infrastructure.businessdate.domain.BusinessDateType;
import org.apache.fineract.infrastructure.core.domain.FineractPlatformTenant;
import org.apache.fineract.infrastructure.core.service.ThreadLocalContextUtil;
import org.apache.fineract.organisation.monetary.domain.MonetaryCurrency;
import org.apache.fineract.organisation.monetary.domain.Money;
import org.apache.fineract.organisation.monetary.domain.MoneyHelper;
import org.apache.fineract.organisation.office.domain.Office;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.Mockito;
import org.springframework.test.util.ReflectionTestUtils;

public class LoanTransactionChargePortionAlignmentTest {

    private static final MonetaryCurrency KES = new MonetaryCurrency("KES", 2, null);

    private RoundingMode originalRoundingMode;
    private MathContext originalMathContext;

    @BeforeEach
    void setUp() {
        this.originalRoundingMode = (RoundingMode) ReflectionTestUtils.getField(MoneyHelper.class, "roundingMode");
        this.originalMathContext = (MathContext) ReflectionTestUtils.getField(MoneyHelper.class, "mathContext");
        ReflectionTestUtils.setField(MoneyHelper.class, "roundingMode", RoundingMode.HALF_EVEN);
        ReflectionTestUtils.setField(MoneyHelper.class, "mathContext", new MathContext(12, RoundingMode.HALF_EVEN));
        ThreadLocalContextUtil.setTenant(new FineractPlatformTenant(1L, "default", "Default", "Africa/Nairobi", null));
        ThreadLocalContextUtil.setBusinessDates(new HashMap<>(Map.of(BusinessDateType.BUSINESS_DATE, LocalDate.of(2024, 1, 1))));
    }

    @AfterEach
    void tearDown() {
        ReflectionTestUtils.setField(MoneyHelper.class, "roundingMode", this.originalRoundingMode);
        ReflectionTestUtils.setField(MoneyHelper.class, "mathContext", this.originalMathContext);
        ThreadLocalContextUtil.clearTenant();
    }

    @Test
    public void excessFeePortionMovesToOverpayment() {
        final Office office = Mockito.mock(Office.class);
        final LoanTransaction transaction = LoanTransaction.repayment(office, Money.of(KES, BigDecimal.valueOf(100)), null,
                LocalDate.of(2024, 1, 1), null);
        transaction.updateComponents(Money.zero(KES), Money.zero(KES), Money.of(KES, BigDecimal.valueOf(30)), Money.zero(KES));

        transaction.reduceExcessChargePortionToOverpayment(KES, Money.of(KES, BigDecimal.valueOf(10)), false);

        assertEquals(0, BigDecimal.valueOf(20).compareTo(transaction.getFeeChargesPortion(KES).getAmount()));
        assertEquals(0, BigDecimal.valueOf(10).compareTo(transaction.getOverPaymentPortion(KES).getAmount()));
        assertNull(transaction.getPenaltyChargesPortion(KES).getAmountDefaultedToNullIfZero());
    }
}
